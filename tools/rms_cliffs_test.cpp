                const bool exists=selectRmsCliffArt({e,south,w,n},state,art);
                mix(exists); mix(state);
                if (exists) {
                    mix(art.unit); mix(art.facet); mix(uint32_t(art.offsetX*2)); mix(uint32_t(art.offsetY*2));
                } else assert(state==artSeeds[k] && art.unit==-1);
